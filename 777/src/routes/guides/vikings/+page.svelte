<h1>Viking vengeance</h1>

<section class="tldr">
	<h2>TL;DR</h2>
	<ul>
		<li>
			<strong>Empty your castle.</strong> Trade your troops and spare heroes out to other members. Leftover
			troops of your own cut the score of everyone supporting you.
		</li>
		<li>
			<strong>Top 3 heroes in the Guard Station</strong>, strongest first. Everything else goes out on
			exchange.
		</li>
		<li>
			<strong>Do not heal mid-event.</strong> Healing pulls your troops home and tanks your supporters'
			scores. Only heal before the second failure ends it, or in the recall between stages 9 and 10.
		</li>
		<li>
			<strong>Stages 10 and 20 are HQ.</strong> Shield infantry above tier 8 plus a little cavalry —
			follow whatever your leadership specifies.
		</li>
		<li>
			<strong>Reinforce with infantry and cavalry.</strong> Vikings hit infantry first, cavalry second,
			archers last — leave archers home if your march is full.
		</li>
		<li>
			<strong>Be online for stages 7, 14 and 17.</strong> Those only hit online players and score the
			highest.
		</li>
		<li>
			<strong>Reinforce empty, uncrowded cities.</strong> Points split by share of kills, so avoid
			doubling up with a whale.
		</li>
		<li>
			<strong>Pair up with similar power.</strong> Groups of two or six, positioned close together, so
			support arrives fast within the 1-minute gap.
		</li>
	</ul>
</section>

<h2>Details</h2>

<dl class="qa">
	<dt>How does scoring work?</dt>
	<dd>
		You score by killing Vikings attacking castles — mostly other people's. That's why an empty
		castle is worth more to your alliance than a defended one: supporters get the kills.
	</dd>

	<dt>Why does leaving troops at home hurt?</dt>
	<dd>
		Your own troops soak the kills that would otherwise go to your supporters. Exchange them out so
		your castle is genuinely empty.
	</dd>

	<dt>How much time between stages?</dt>
	<dd>About a minute normally, roughly three minutes for the HQ stages (10 and 20).</dd>

	<dt>What if I have an alt in the alliance?</dt>
	<dd>
		Use its troops to reinforce your main. If you're tier 10, the alt can also defend on its own for
		extra points.
	</dd>

	<dt>When does the event end?</dt>
	<dd>On the second failure.</dd>
</dl>

<h2>Maximizing your points</h2>

<ul>
	<li>
		<strong>Send infantry and cavalry.</strong> Vikings engage infantry first, then cavalry, then archers —
		so infantry and cavalry get into the fight early and take the kills. If your march can't hold
		everything, leave the archers at home.
	</li>
	<li>
		<strong>Reinforce online players.</strong> Waves 7, 14 and 17 only attack members who are online.
		March slots spent on offline allies are wasted, and offline players usually haven't cleared their
		city anyway.
	</li>
	<li>
		<strong>Pick empty, uncrowded cities.</strong> The point pool is split by share of kills. Look for
		an ally with no troops of their own and only one or two other reinforcers. Share a city with a
		whale and their higher-tier troops will siphon most of the kills.
	</li>
	<li>
		<strong>Rotate to HQ for waves 10 and 20.</strong> Those waves hit the Alliance HQ only — no cities.
		Once the wave 9 (or 19) battle report has finished, recall one strong march and send it to HQ, then
		send it back to your ally as soon as the HQ wave ends. Recall too early and you forfeit the
		previous wave's points.
	</li>
	<li>
		<strong>Lead with an offensive hero.</strong> Use your Bear Hunt joiner heroes in the leader slot —
		Chenko, Amadeus, Yeonwoo or Amane — for extra damage and a bigger share of the kills.
	</li>
</ul>

<h2>Tips</h2>

<ul>
	<li>
		<strong>Sort your exchange before it starts.</strong> A botched exchange leaves troops sitting in
		your castle for the whole event.
	</li>
	<li>
		<strong>Agree positions in advance</strong> so nobody is out of support range when a wave lands.
	</li>
</ul>

