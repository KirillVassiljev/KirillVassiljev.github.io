<h1>Strongest governor</h1>

<section class="tldr">
	<h2>TL;DR</h2>
	<ul>
		<li>
			<strong>If KvK is close, save your speed-ups for it.</strong> KvK's server-wide build, research and
			training buffs mean the same speed-ups buy far more power there than in a normal Strongest
			Governor week.
		</li>
		<li><strong>A 7-day points race</strong>, usually monthly. One day, one theme.</li>
		<li>
			<strong>Points come from spending:</strong> building upgrades, hero levels, skill upgrades, troop
			training, speed-ups and rare materials like Truegold and Mithril.
		</li>
		<li>
			<strong>Bank everything beforehand.</strong> Nothing you do outside the event window scores. Sit
			on your speed-ups and resources and dump them on the matching day.
		</li>
		<li>
			<strong>250,000 points</strong> is the bar to qualify for the kingdom-wide rewards. Aim for it even
			if you can't rank.
		</li>
		<li><strong>Grab your 2 Challenge Medals every day</strong> — free rewards for tasks you're already doing.</li>
	</ul>
</section>

<h2>The 7 days</h2>

<ol class="stages">
	<li><strong>Day 1 — City construction:</strong> building upgrades and construction speed-ups.</li>
	<li><strong>Day 2 — Hero development:</strong> hero EXP, shards, star-ups.</li>
	<li><strong>Day 3 — Skill upgrades:</strong> hero skill levels.</li>
	<li><strong>Day 4 — Troop training:</strong> training and promoting troops.</li>
	<li><strong>Day 5 — Skill upgrades again.</strong></li>
	<li><strong>Day 6 — Troop training again.</strong></li>
	<li><strong>Day 7 — Hero development + gathering.</strong></li>
</ol>

<h2>Details</h2>

<dl class="qa">
	<dt>What is it?</dt>
	<dd>
		A recurring competition where every governor scores points for developing their city. It runs
		for seven days and is split into seven stages, one per day.
	</dd>

	<dt>How do I score?</dt>
	<dd>
		By finishing the actions that match the day's theme — upgrading buildings, levelling heroes,
		upgrading skills, training or promoting troops, burning speed-ups, and consuming rare
		resources.
	</dd>

	<dt>What are Challenge Medals?</dt>
	<dd>
		A separate daily currency. You can earn up to 2 a day from tasks; spend them in the Challenge
		Medal Rewards tab. The more you've collected, the better the tier you can claim.
	</dd>

	<dt>Which ranking should I care about?</dt>
	<dd>
		If you're competitive, the cross-kingdom total ranking pays best — Truegold and exclusive
		cosmetics — but you're up against every participating kingdom. Otherwise focus on point
		milestones and hitting 250,000 total.
	</dd>

	<dt>Does spending outside the event count?</dt>
	<dd>No. Only actions completed during the event window score points.</dd>
</dl>

<h2>Rewards</h2>

<ul>
	<li>
		<strong>Point milestones:</strong> 5 tiers per day, each needing more points than the last. Claim
		them as you go.
	</li>
	<li><strong>Challenge Medal rewards:</strong> claimed with the medals you earn, up to 2 per day.</li>
	<li>
		<strong>Daily stage ranking:</strong> paid at the end of each day to the top 1,000 scorers in
		your kingdom — gems and speed-ups, scaled by rank.
	</li>
	<li>
		<strong>Kingdom total ranking:</strong> top 1,000 in your kingdom by total points across the 7
		days.
	</li>
	<li>
		<strong>Cross-kingdom ranking:</strong> top 2,000 across all participating kingdoms. Much better
		rewards — Truegold and exclusive cosmetics — and much harder.
	</li>
	<li>
		<strong>Kingdom rewards:</strong> given to everyone in a participating kingdom based on where the
		kingdom places, but you must personally earn 250,000 points to qualify.
	</li>
</ul>

<h2>Tips</h2>

<ul>
	<li>
		<strong>Stockpile before the event.</strong> Hold speed-ups, hero EXP, shards and Truegold and
		spend them only on the matching day.
	</li>
	<li>
		<strong>Pick one day to go big.</strong> Daily stage rewards are per-day, so concentrating your
		hoard on a single stage ranks you higher than spreading it thin.
	</li>
	<li>
		<strong>Skills and troops come round twice</strong> (days 3/5 and 4/6). Split your skill books and
		training between the pair rather than blowing everything on the first.
	</li>
	<li>
		<strong>Queue long upgrades to finish inside the window.</strong> Points land when the action
		completes, not when you start it.
	</li>
	<li>
		<strong>Claim milestones and medals daily.</strong> They don't carry over.
	</li>
</ul>

